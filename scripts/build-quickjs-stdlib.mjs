import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";
const require = createRequire(import.meta.url);
const streamRequire = createRequire(require.resolve("readable-stream"));
const root = fileURLToPath(new URL("../", import.meta.url));
export async function buildQuickJsStdlib() {
  const result = await build({
    configFile: false,
    publicDir: false,
    logLevel: "error",
    resolve: { alias: [
      { find: /^abort-controller$/, replacement: streamRequire.resolve("abort-controller/dist/abort-controller.js") },
      { find: /^buffer$/, replacement: root + "node_modules/buffer/index.js" },
      { find: /^events$/, replacement: root + "node_modules/events/events.js" },
      { find: /^process\/?$/, replacement: root + "src/runtime/quickjs/process.cjs" },
    ] },
    build: { write: false, target: "es2020", minify: "esbuild", lib: {
      entry: root + "src/runtime/quickjs/node-stdio.js", formats: ["iife"], name: "__nodeStdio",
    } },
  });
  const chunk = (Array.isArray(result) ? result[0] : result).output.find((item) => item.type === "chunk");
  const bufferTypes = await readFile(root + "node_modules/buffer/index.d.ts", "utf8");
  const declarations = 'declare module "buffer" {\n' + bufferTypes + '\nconst buffer: { Buffer: typeof Buffer }; export default buffer;\n}\n';
  await writeFile(root + "src/runtime/quickjs/stdlib.generated.ts", "// Generated by scripts/build-quickjs-stdlib.mjs.\nexport const QUICKJS_NODE_STDLIB = " + JSON.stringify(chunk.code) + ";\nexport const QUICKJS_BUFFER_DECLARATION = " + JSON.stringify(declarations) + ";\n");
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildQuickJsStdlib();
